import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const rows=JSON.parse(await fs.readFile('tmp/coords/rows.json','utf8'));
const wb=Workbook.create();const sh=wb.worksheets.add('좌표');
sh.getRange('A1:C175').values=[['번호','X','Y'],...rows];
sh.showGridLines=false;
sh.getRange('A1:C175').format.font={name:'Arial',size:11};
sh.getRange('A1:C175').format.rowHeight=21;
sh.getRange('A1:C175').format.verticalAlignment='center';
sh.getRange('A1:A175').format.columnWidth=15;
sh.getRange('B1:C175').format.columnWidth=20;
sh.getRange('B2:C175').setNumberFormat('0.00');
sh.getRange('A1:C1').format={fill:'#26445B',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},horizontalAlignment:'center'};
sh.freezePanes.freezeRows(1);
sh.tables.add('A1:C175',true,'Coordinates');
wb.recalculate();
if(JSON.stringify(sh.getRange('A2:C175').values)!==JSON.stringify(rows))throw Error('Value mismatch');
console.log((await wb.inspect({kind:'table',range:'좌표!A1:C5',include:'values',tableMaxRows:5,tableMaxCols:3})).ndjson);
const out='outputs/01a08378-055c-7ef3-aa85-8034aad88e28';
await fs.mkdir(out,{recursive:true});
const png=await wb.render({sheetName:'좌표',range:'A1:C12',scale:2,format:'png'});
await fs.writeFile('tmp/coords/preview.png',new Uint8Array(await png.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(out+'/지번별조서_번호_XY좌표.xlsx');
